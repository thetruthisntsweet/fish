"""Server settings read from the environment (T2.1 subtasks 9, 13 and 14).

Two database identities (T2.1 §11):

* **Admin** (``FISH_ADMIN_DATABASE_URL``): the database owner. Runs migrations, creates the
  server's login, and does withdrawals and exports. Never used to serve players.
* **App** (derived): the login the running server uses, ``fish_server`` unless
  ``FISH_APP_DB_USER`` says otherwise. It may read and add rows, but never change or delete
  them. Its URL is the admin URL with the user swapped for that login and the password
  taken from ``FISH_APP_DB_PASSWORD``, so there is no second URL to keep in step.

Nothing secret is ever written in the repository. Locally the values come from ``.env``;
on Render, from ``render.yaml`` (the admin URL from the database link, the app password
generated by Render).
"""

import os
import re

from sqlalchemy import make_url

ADMIN_DATABASE_URL_VAR = "FISH_ADMIN_DATABASE_URL"
APP_PASSWORD_VAR = "FISH_APP_DB_PASSWORD"
APP_USER_VAR = "FISH_APP_DB_USER"
DEFAULT_APP_LOGIN_ROLE = "fish_server"
"""The login the running server connects as (created by ``fish_server.privileges``)."""

_ROLE_NAME_PATTERN = re.compile(r"[a-z_][a-z0-9_]{0,62}")

_DRIVER_PREFIX = "postgresql+psycopg://"
_PLAIN_PREFIXES = ("postgresql://", "postgres://")


def normalize_database_url(url: str) -> str:
    """Make a PostgreSQL URL use the psycopg 3 driver.

    Hosting platforms (Render included) hand out plain ``postgresql://`` URLs. SQLAlchemy
    would read those as "use the psycopg2 driver", which is not installed, so the scheme is
    rewritten. URLs that already name a driver are returned unchanged.
    """
    url = url.strip()
    for prefix in _PLAIN_PREFIXES:
        if url.startswith(prefix):
            return _DRIVER_PREFIX + url.removeprefix(prefix)
    return url


def _required(var: str) -> str:
    value = os.environ.get(var, "").strip()
    if not value:
        raise RuntimeError(
            f"{var} is not set. Copy .env.example to .env and run commands "
            "with `uv run --env-file .env ...`."
        )
    return value


def admin_database_url() -> str:
    """URL of the database as its owner: for migrations and admin tools only."""
    return normalize_database_url(_required(ADMIN_DATABASE_URL_VAR))


def app_login_role() -> str:
    """Name of the server's login: FISH_APP_DB_USER, or ``fish_server`` if unset.

    Only ever changed by the test suite, which uses its own login so that running the tests
    never touches the password of the login your development server uses: logins belong to
    the whole database server, not to one database.
    """
    name = os.environ.get(APP_USER_VAR, "").strip() or DEFAULT_APP_LOGIN_ROLE
    if not _ROLE_NAME_PATTERN.fullmatch(name):
        raise ValueError(f"{APP_USER_VAR} must be lowercase letters, digits and _; got {name!r}")
    return name


def app_password() -> str:
    """The password of the ``fish_server`` login."""
    return _required(APP_PASSWORD_VAR)


def database_url() -> str:
    """URL the running server uses: the admin URL, logged in as the server's login instead."""
    url = make_url(admin_database_url()).set(username=app_login_role(), password=app_password())
    return url.render_as_string(hide_password=False)

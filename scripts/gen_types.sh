#!/usr/bin/env bash
# Python message models -> JSON Schema (schemas/) -> TypeScript (client/src/generated/).
#
#   scripts/gen_types.sh          regenerate both folders; commit the result
#   scripts/gen_types.sh --check  regenerate into a temporary folder and fail if anything
#                                 differs from the committed files (used by check.sh and CI)
set -euo pipefail
cd "$(dirname "$0")/.."

schemas_dir="schemas"
ts_dir="client/src/generated"
if [[ "${1:-}" == "--check" ]]; then
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  schemas_dir="$tmp/schemas"
  ts_dir="$tmp/generated"
  mkdir -p "$ts_dir"
fi

uv run python -m fish_server.schema_export "$schemas_dir" > /dev/null

# One .ts file per schema. Remove old ones first so a deleted message leaves nothing behind.
find "$ts_dir" -maxdepth 1 -name "*.ts" -delete
for schema in "$schemas_dir"/*.json; do
  name="$(basename "$schema" .json)"
  client/node_modules/.bin/json2ts \
    --input "$schema" \
    --output "$ts_dir/$name.ts" \
    --additionalProperties=false \
    --unknownAny \
    --bannerComment="// GENERATED by scripts/gen_types.sh from schemas/$name.json. Do not edit."
done

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -r schemas "$schemas_dir" > /dev/null \
     || ! diff -r --exclude=README.md client/src/generated "$ts_dir" > /dev/null; then
    echo "Generated types are out of date. Run scripts/gen_types.sh and commit the result." >&2
    diff -r schemas "$schemas_dir" || true
    diff -r --exclude=README.md client/src/generated "$ts_dir" || true
    exit 1
  fi
  echo "Generated types are up to date."
fi